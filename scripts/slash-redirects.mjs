// Post-build: permanent (301) redirects from slashless URLs to the trailing-slash
// version for every built page. Without these, Cloudflare's asset handling
// answers with a temporary 307.
import { readdirSync, statSync, readFileSync, appendFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const root = 'dist/client';
const pages = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else if (name === 'index.html' && dir !== root) pages.push('/' + dir.slice(root.length + 1) + '/');
  }
})(root);

const file = join(root, '_redirects');
const existing = existsSync(file) ? readFileSync(file, 'utf8') : '';
const lines = pages
  .map((p) => p.slice(0, -1))
  .filter((from) => !existing.split('\n').some((l) => l.split(/\s+/)[0] === from))
  .map((from) => `${from} ${from}/ 301`);
appendFileSync(file, `\n# Slashless page URLs (generated by scripts/slash-redirects.mjs)\n${lines.join('\n')}\n`);
console.log(`[slash-redirects] ${lines.length} redirects`);
